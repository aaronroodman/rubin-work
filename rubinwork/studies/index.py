"""Write ``STUDIES.md``: every study, its status, answer and products used."""

import pathlib

from .core import find_studies, load_study, repo_root

__all__ = ["studies_markdown", "write_index"]


def _cell(text):
    """One value as a Markdown table cell: one line, pipes escaped."""
    return " ".join(str(text or "").split()).replace("|", "\\|")


def studies_markdown(root=None):
    """The text of ``STUDIES.md``.

    Deterministic: the text depends only on the ``study.md`` files. The "last
    updated" date is the latest Log entry over all studies, not today's.

    Parameters
    ----------
    root : `str` or `pathlib.Path`, optional
        Repository root, `repo_root` by default.

    Returns
    -------
    text : `str`
        Markdown.
    """
    root = pathlib.Path(root) if root else repo_root()
    studies = [load_study(p) for p in find_studies(root)]
    dates = [d for s in studies for d in [s.last_log_date(), s.meta.get("started")] if d]
    updated = max(dates) if dates else "never"
    lines = [
        "# Studies",
        "",
        f"> **Status:** generated · **Last updated:** {updated} · **Kind:** reference "
        "(index)",
        "",
        "Every study in the repository, read from the front matter of "
        "`<topic>/<study>/study.md`. Generated by `python -m rubinwork.studies index`; "
        "do not edit by hand. Status is one of active, answered (question answered, "
        "work may continue), parked, done or dropped. Products are "
        "`variant@build`, as listed in [`PRODUCTS.md`](PRODUCTS.md).",
        "",
        "| study | status | started | last log | question | answer | products used |",
        "|---|---|---|---|---|---|---|",
    ]
    for s in studies:
        rel = s.path.relative_to(root).as_posix()
        uses = "; ".join(f"{p}: {v}" for p, v in sorted((s.meta.get("uses") or {}).items()))
        lines.append(
            f"| [{s.key}]({rel}) | {_cell(s.status)} | {_cell(s.meta.get('started'))} "
            f"| {_cell(s.last_log_date())} | {_cell(s.meta.get('question'))} "
            f"| {_cell(s.meta.get('answer'))} | {_cell(uses)} |")
    return "\n".join(lines) + "\n"


def write_index(root=None, target=None):
    """Write ``STUDIES.md``, touching the file only if its text changes.

    Parameters
    ----------
    root : `str` or `pathlib.Path`, optional
        Repository root, `repo_root` by default.
    target : `str` or `pathlib.Path`, optional
        Output file, ``<root>/STUDIES.md`` by default.

    Returns
    -------
    changed : `bool`
        Whether the file was written.
    """
    root = pathlib.Path(root) if root else repo_root()
    target = pathlib.Path(target) if target else root / "STUDIES.md"
    text = studies_markdown(root)
    if target.is_file() and target.read_text() == text:
        return False
    target.write_text(text)
    return True
