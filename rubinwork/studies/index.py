"""Write ``STUDIES.md`` and the generated block of each topic ``README.md``.

``STUDIES.md`` lists every study, its status, answer and products used. A topic README
keeps its hand-written text; only the lines between `BEGIN` and `END` are rewritten, with
the table of that topic's studies.
"""

import pathlib

from .core import find_studies, load_study, repo_root

__all__ = ["studies_markdown", "write_index", "topic_block", "write_topic_readme",
           "write_topic_readmes", "BEGIN", "END"]

BEGIN = "<!-- BEGIN generated: python -m rubinwork.studies index -->"
END = "<!-- END generated -->"


def _cell(text):
    """One value as a Markdown table cell: one line, pipes escaped."""
    return " ".join(str(text or "").split()).replace("|", "\\|")


def studies_markdown(root=None):
    """The text of ``STUDIES.md``.

    Deterministic: the text depends only on the ``study.md`` files. The "last
    updated" date is the latest Log entry over all studies, not today's.

    Parameters
    ----------
    root : `str` or `pathlib.Path`, optional
        Repository root, `repo_root` by default.

    Returns
    -------
    text : `str`
        Markdown.
    """
    root = pathlib.Path(root) if root else repo_root()
    studies = [load_study(p) for p in find_studies(root)]
    dates = [d for s in studies for d in [s.last_log_date(), s.meta.get("started")] if d]
    updated = max(dates) if dates else "never"
    lines = [
        "# Studies",
        "",
        f"> **Status:** generated · **Last updated:** {updated} · **Kind:** reference "
        "(index)",
        "",
        "Every study in the repository, read from the front matter of "
        "`<topic>/<study>/study.md`. Generated by `python -m rubinwork.studies index`; "
        "do not edit by hand. Status is one of active, answered (question answered, "
        "work may continue), parked, done or dropped. Products are "
        "`variant@build`, as listed in [`PRODUCTS.md`](PRODUCTS.md).",
        "",
        "| study | status | started | last log | question | answer | products used |",
        "|---|---|---|---|---|---|---|",
    ]
    for s in studies:
        rel = s.path.relative_to(root).as_posix()
        uses = "; ".join(f"{p}: {v}" for p, v in sorted((s.meta.get("uses") or {}).items()))
        lines.append(
            f"| [{s.key}]({rel}) | {_cell(s.status)} | {_cell(s.meta.get('started'))} "
            f"| {_cell(s.last_log_date())} | {_cell(s.meta.get('question'))} "
            f"| {_cell(s.meta.get('answer'))} | {_cell(uses)} |")
    return "\n".join(lines) + "\n"


def write_index(root=None, target=None):
    """Write ``STUDIES.md``, touching the file only if its text changes.

    Parameters
    ----------
    root : `str` or `pathlib.Path`, optional
        Repository root, `repo_root` by default.
    target : `str` or `pathlib.Path`, optional
        Output file, ``<root>/STUDIES.md`` by default.

    Returns
    -------
    changed : `bool`
        Whether the file was written.
    """
    root = pathlib.Path(root) if root else repo_root()
    target = pathlib.Path(target) if target else root / "STUDIES.md"
    text = studies_markdown(root)
    if target.is_file() and target.read_text() == text:
        return False
    target.write_text(text)
    return True


def topic_block(topic, root=None):
    """The generated block of one topic README: a table of its studies.

    Parameters
    ----------
    topic : `str`
        Topic name.
    root : `str` or `pathlib.Path`, optional
        Repository root, `repo_root` by default.

    Returns
    -------
    text : `str`
        Markdown from `BEGIN` to `END` inclusive, or an empty string if the topic has
        no study.
    """
    root = pathlib.Path(root) if root else repo_root()
    studies = [load_study(p) for p in find_studies(root, topic=topic)]
    if not studies:
        return ""
    lines = [BEGIN, "", "## Studies", "",
             "Generated from each `<study>/study.md`; edit those, not this table.", "",
             "| study | status | last log | answer |", "|---|---|---|---|"]
    for s in studies:
        answer = s.meta.get("answer") or s.meta.get("question")
        lines.append(f"| [{s.name}]({s.name}/study.md) | {_cell(s.status)} "
                     f"| {_cell(s.last_log_date())} | {_cell(answer)} |")
    lines += ["", END]
    return "\n".join(lines) + "\n"


def write_topic_readme(topic, root=None):
    """Rewrite the generated block of ``<topic>/README.md``, keeping the rest.

    A README with no block gets one after its first paragraph; a topic with no README
    gets one holding a heading and the block.

    Parameters
    ----------
    topic : `str`
        Topic name.
    root : `str` or `pathlib.Path`, optional
        Repository root, `repo_root` by default.

    Returns
    -------
    changed : `bool`
        Whether the file was written.
    """
    root = pathlib.Path(root) if root else repo_root()
    block = topic_block(topic, root)
    if not block:
        return False
    path = root / topic / "README.md"
    old = path.read_text() if path.is_file() else f"# {topic}\n"
    if BEGIN in old and END in old:
        head, rest = old.split(BEGIN, 1)
        tail = rest.split(END, 1)[1].lstrip("\n")
        new = head + block + ("\n" + tail if tail else "")
    else:
        parts = old.split("\n\n", 2)
        if len(parts) == 3:
            new = parts[0] + "\n\n" + parts[1] + "\n\n" + block + "\n" + parts[2]
        else:
            new = old.rstrip("\n") + "\n\n" + block
    if new == old:
        return False
    path.write_text(new)
    return True


def write_topic_readmes(root=None):
    """`write_topic_readme` for every topic that has a study.

    Returns
    -------
    changed : `list` [`str`]
        Topics whose README was written.
    """
    root = pathlib.Path(root) if root else repo_root()
    topics = sorted({p.parent.parent.name for p in find_studies(root)})
    return [t for t in topics if write_topic_readme(t, root)]
